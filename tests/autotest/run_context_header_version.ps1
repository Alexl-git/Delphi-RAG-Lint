<#
  run_context_header_version.ps1 -- the context bundle header must carry the
  version `--version` reports (Gitea drag-lint#19).

  THE DEFECT. The markdown bundle said "Generated by drag-lint v0.18" -- the
  release that introduced it -- while `--version` said 1.18.0-alpha, so a
  reader comparing outputs could not tell which build produced a bundle.

  WHAT THIS ASSERTS
    1. the header names the exact version `--version` prints     <- THE FIX
    2. CONTROL: the bundle still resolves the routine (its body is there)

  RED-CHECK: against the pre-fix build 1 FAILS ("v0.18"); 2 passes on both.
#>
[CmdletBinding()]
param(
  [string]$Exe = "$PSScriptRoot\..\..\src\cli\Win64\Debug\drag-lint.exe"
)
try {
$ErrorActionPreference = 'Stop'
$script:Failed = $false
function Check($n, $ok, $d = '') {
  $s = if ($ok) { 'PASS' } else { 'FAIL' }
  $c = if ($ok) { 'Green' } else { 'Red' }
  Write-Host ("  [{0}] {1} {2}" -f $s, $n, $d) -ForegroundColor $c
  if (-not $ok) { $script:Failed = $true }
}

if (-not (Test-Path $Exe)) { Write-Host "FATAL: exe not found: $Exe" -ForegroundColor Red; exit 2 }
$Exe = (Resolve-Path $Exe).Path

function Write-Ascii([string]$path, [string]$text) {
  $dir = Split-Path -Parent $path
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory $dir -Force | Out-Null }
  [System.IO.File]::WriteAllText($path, ($text -replace "`r?`n", "`r`n"), [System.Text.Encoding]::ASCII)
}

$work = Join-Path C:\TEMP "draglint_ctxver_$PID"
if (Test-Path $work) { Get-ChildItem $work -Recurse -Force | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue }
New-Item -ItemType Directory $work -Force | Out-Null

$dir = Join-Path $work 'p'
Write-Ascii (Join-Path $dir 'Ver.dpr') @'
program Ver;

uses
  UVer in 'UVer.pas';

begin
end.
'@
Write-Ascii (Join-Path $dir 'UVer.pas') @'
unit UVer;

interface

function Twice(A: Integer): Integer;

implementation

function Twice(A: Integer): Integer;
begin
  Result := A + A;
end;

end.
'@
$db = Join-Path $work 'v.sqlite'
& $Exe index --project (Join-Path $dir 'Ver.dpr') --db $db *> $null

$verLine = (& $Exe --version 2>$null | Select-Object -First 1)
$ver = ''
if ($verLine -match '^drag-lint\s+(\S+)') { $ver = $Matches[1] }
Write-Host "--version: $verLine" -ForegroundColor DarkGray

$ctx = (& $Exe context --task 'modify UVer.Twice' --db $db --format markdown 2>$null) -join "`n"
$hdr = @($ctx -split "`n" | Where-Object { $_ -match 'Generated by drag-lint' })
Write-Host ($hdr -join ' | ') -ForegroundColor DarkGray

Check '1. the header names the --version version' `
  (($ver -ne '') -and ($hdr.Count -ge 1) -and ($hdr[0] -match ('Generated by drag-lint v?' + [regex]::Escape($ver) + ' at '))) "ver=$ver header=$($hdr -join ' | ')"
Check '2. CONTROL: the bundle carries the routine body' ($ctx -match 'Result := A \+ A;') ''

Write-Host ''
if ($script:Failed) { Write-Host 'FAIL' -ForegroundColor Red; exit 1 }
Write-Host 'PASS' -ForegroundColor Green
exit 0
} finally {
  foreach ($d23 in @((Join-Path C:\TEMP "draglint_ctxver_$PID"))) { if (Test-Path -LiteralPath $d23) { Remove-Item -LiteralPath $d23 -Recurse -Force -ErrorAction SilentlyContinue } }
}
