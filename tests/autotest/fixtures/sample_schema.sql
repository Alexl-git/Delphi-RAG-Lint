/* Tiny Firebird DDL fixture for drag-lint v0.40.5 SQL extractor tests.
   Mirrors the patterns in real MS*.SQL files at smaller scale. */

CREATE DOMAIN D_INTEGER AS INTEGER;
CREATE DOMAIN D_VARCHAR40 AS VARCHAR(40);

CREATE GENERATOR GEN_SAMPLE_ID;

CREATE TABLE SAMPLE (
  ID    D_INTEGER NOT NULL,
  NAME  D_VARCHAR40,
  PRIMARY KEY (ID)
);

CREATE TABLE SAMPLE_CHILD (
  CHILD_ID   D_INTEGER NOT NULL,
  SAMPLE_ID  D_INTEGER NOT NULL,
  PRIMARY KEY (CHILD_ID)
);

CREATE INDEX IDX_SAMPLE_NAME ON SAMPLE (NAME);

CREATE EXCEPTION SAMPLE_NOT_FOUND 'Sample row not found.';

CREATE OR ALTER TRIGGER SAMPLE_BI FOR SAMPLE
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = GEN_ID(GEN_SAMPLE_ID, 1);
END;

CREATE OR ALTER PROCEDURE SAMPLE_COUNT
RETURNS (CNT D_INTEGER)
AS
BEGIN
  SELECT COUNT(*) FROM SAMPLE INTO :CNT;
  SUSPEND;
END;
